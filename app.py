
import os
import secrets
import math
import psycopg
from psycopg.rows import dict_row
from functools import wraps

from flask import (
    Flask, render_template, request,
    redirect, url_for, session, flash, g
)
from werkzeug.security import generate_password_hash, check_password_hash

app = Flask(__name__)

app.config["SECRET_KEY"] = os.environ.get("SECRET_KEY") or secrets.token_hex(32)
app.config["SESSION_COOKIE_HTTPONLY"] = True
app.config["SESSION_COOKIE_SAMESITE"] = "Lax"


def get_db():
    if "db" not in g:
        database_url = os.environ.get("DATABASE_URL")
        if not database_url:
            raise RuntimeError("DATABASE_URL is not configured.")

        g.db = psycopg.connect(
            database_url,
            row_factory=dict_row
        )
    return g.db


@app.teardown_appcontext
def close_db(error=None):
    db = g.pop("db", None)
    if db is not None:
        db.close()


def init_db():
    with app.app_context():
        db = get_db()

        db.execute("""
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                full_name TEXT NOT NULL,
                student_id TEXT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS savings (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id)
                    ON DELETE CASCADE,
                amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
                note TEXT DEFAULT '',
                saved_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        db.execute("""
            CREATE TABLE IF NOT EXISTS expenses (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER NOT NULL REFERENCES users(id)
                    ON DELETE CASCADE,
                amount DOUBLE PRECISION NOT NULL CHECK (amount > 0),
                category TEXT NOT NULL,
                note TEXT DEFAULT '',
                spent_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
            )
        """)

        db.commit()


def login_required(view):
    @wraps(view)
    def wrapped_view(*args, **kwargs):
        if "user_id" not in session:
            flash("Please log in first.")
            return redirect(url_for("login"))
        return view(*args, **kwargs)
    return wrapped_view


@app.route("/")
def home():
    if "user_id" in session:
        return redirect(url_for("dashboard"))
    return redirect(url_for("login"))


@app.route("/register", methods=["GET", "POST"])
def register():
    if request.method == "POST":
        full_name = request.form.get("full_name", "").strip()
        student_id = request.form.get("student_id", "").strip()
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        if not all([full_name, student_id, email, password]):
            flash("Please complete all fields.")
            return render_template("register.html")

        if len(password) < 8:
            flash("Password must be at least 8 characters.")
            return render_template("register.html")

        db = get_db()
        try:
            db.execute(
                """INSERT INTO users
                   (full_name, student_id, email, password_hash)
                   VALUES (%s, %s, %s, %s)""",
                (
                    full_name,
                    student_id,
                    email,
                    generate_password_hash(password),
                ),
            )
            db.commit()

        except psycopg.IntegrityError:
            db.rollback()
            flash("That email or student ID is already registered.")
            return render_template("register.html")

        flash("Account created! You can now log in.")
        return redirect(url_for("login"))

    return render_template("register.html")


@app.route("/login", methods=["GET", "POST"])
def login():
    if request.method == "POST":
        email = request.form.get("email", "").strip().lower()
        password = request.form.get("password", "")

        user = get_db().execute(
            "SELECT * FROM users WHERE email = %s",
            (email,),
        ).fetchone()

        if user is None or not check_password_hash(
            user["password_hash"], password
        ):
            flash("Incorrect email or password.")
            return render_template("login.html")

        session.clear()
        session["user_id"] = user["id"]
        return redirect(url_for("dashboard"))

    return render_template("login.html")


@app.route("/dashboard")
@login_required
def dashboard():
    db = get_db()

    user = db.execute(
        """SELECT id, full_name, student_id, email
           FROM users WHERE id = %s""",
        (session["user_id"],),
    ).fetchone()

    if user is None:
        session.clear()
        return redirect(url_for("login"))

    savings = db.execute(
        """SELECT id, amount, note, saved_at
           FROM savings WHERE user_id = %s
           ORDER BY saved_at DESC, id DESC""",
        (user["id"],),
    ).fetchall()

    total = sum(item["amount"] for item in savings)

    expenses = db.execute(
        """SELECT id, amount, category, note, spent_at
           FROM expenses
           WHERE user_id = %s
           ORDER BY spent_at DESC, id DESC""",
        (user["id"],),
    ).fetchall()

    total_expenses = sum(item["amount"] for item in expenses)
    balance = total - total_expenses

    return render_template(
        "index.html",
        user=user,
        savings=savings,
        expenses=expenses,
        total=total,
        total_expenses=total_expenses,
        balance=balance,
    )


@app.route("/add_expense", methods=["POST"])
@login_required
def add_expense():
    amount_text = request.form.get("amount", "").strip()
    category = request.form.get("category", "").strip()
    note = request.form.get("note", "").strip()

    try:
        amount = float(amount_text)
    except ValueError:
        flash("Please enter a valid expense amount.")
        return redirect(url_for("dashboard"))

    if not math.isfinite(amount) or amount <= 0:
        flash("Expense must be greater than ₱0.")
        return redirect(url_for("dashboard"))

    if category not in [
        "Food", "Transportation", "School Supplies",
        "Personal", "Other"
    ]:
        flash("Please select a valid expense category.")
        return redirect(url_for("dashboard"))

    if len(note) > 200:
        flash("The note must be 200 characters or fewer.")
        return redirect(url_for("dashboard"))

    db = get_db()

    total_saved = db.execute(
        """SELECT COALESCE(SUM(amount), 0) AS total
           FROM savings WHERE user_id = %s""",
        (session["user_id"],),
    ).fetchone()["total"]

    total_spent = db.execute(
        """SELECT COALESCE(SUM(amount), 0) AS total
           FROM expenses WHERE user_id = %s""",
        (session["user_id"],),
    ).fetchone()["total"]

    if amount > total_saved - total_spent:
        flash("You don't have enough remaining savings for this expense.")
        return redirect(url_for("dashboard"))

    db.execute(
        """INSERT INTO expenses (user_id, amount, category, note)
           VALUES (%s, %s, %s, %s)""",
        (session["user_id"], amount, category, note),
    )
    db.commit()

    flash("Expense recorded successfully!")
    return redirect(url_for("dashboard"))


